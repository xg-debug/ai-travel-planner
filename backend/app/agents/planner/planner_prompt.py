from typing import Any, Dict

from app.agents.shared import normalize_preferences


def build_planner_prompt(state: Dict[str, Any]) -> str:
    city = state["city"]
    preferences = normalize_preferences(state.get("preferences", []) or [])
    budget = state.get("budget", "中等")
    travelers = state.get("travelers", 1)
    return f"""
你是旅行规划系统中的 Planner agent。
你的任务不是直接生成完整行程，而是先把用户需求拆解成“可执行的结构化规划意图”，供后续搜索、筛选和排期使用。

请基于以下信息，输出高质量、可落地、强旅游导向的规划结果。

【输入信息】
城市：{city}
天数：{state['days']}
人数：{travelers}
预算：{budget}
偏好：{', '.join(preferences) if preferences else '无特殊偏好'}
需求：{state['query']}

【你的目标】
1. 准确理解用户这次出行的旅行风格与核心诉求。
2. 将需求拆解为适合后续搜索的景点、美食、酒店查询词。
3. 查询词必须具体、真实、具有旅游决策价值，避免空泛表达。
4. 输出内容应优先体现“这个城市最值得体验的内容”以及“与用户偏好强相关的内容”。


【返回格式】
仅返回一个 JSON 对象，不要添加任何解释、注释、Markdown 或代码块。
JSON 结构如下：
{{
  "travel_style": "一句话总结出行风格",
  "planning_focus": "一句话说明路线规划重点",
  "attraction_queries": ["用于搜索景点与城市体验的查询词，3到6个"],
  "food_queries": ["用于搜索本地代表性餐饮体验的查询词，3到6个"],
  "hotel_queries": ["用于搜索酒店的查询词，2到4个"],
  "must_have": ["本次行程必须覆盖的体验类型，4到8个"]
}}

【字段要求】
- travel_style：
  用一句自然语言概括用户的旅行类型，例如“适合第一次到访的经典城市漫游”“亲子友好的轻松度假型行程”“以美食与夜生活为主的周末旅行”。

- planning_focus：
  用一句话指出后续路线规划时最重要的原则，例如“优先按区域串联核心地标，减少跨城通勤”“以博物馆与历史街区为主，穿插夜间体验”“围绕亲子体验和休息节奏安排”。

- attraction_queries：
  这些查询词用于后续搜索景点和城市体验。
  必须满足以下要求：
  1. 优先包含真正有代表性的地标、历史街区、核心博物馆、城市名片、观景体验、经典散步区域。
  2. 应体现“游客到这座城市最值得去什么”，不要只给宽泛类别。
  3. 可结合用户偏好补充，如艺术、建筑、亲子、拍照、夜景、购物、海边、在地文化等。
  4. 不要写过于空泛的词，如“城市公园”“热门景点”“市区逛逛”。
  5. 查询词要像真实搜索会使用的短语，而不是解释句子。

- food_queries：
  这些查询词用于后续搜索餐饮。
  必须满足以下要求：
  1. 优先覆盖本地特色早餐、老字号、代表性小吃、经典正餐、夜间美食或夜市/酒吧街区。
  2. 优先体现城市在地特色，而不是泛泛的“好吃的餐厅”。
  3. 要兼顾不同用餐场景，例如早餐、午餐/晚餐、夜宵/夜生活。
  4. 不要写“酒店周边早餐”“网红餐厅推荐”这类弱信息词。
  5. 查询词应便于检索到真实餐厅、街区或菜系体验。

- hotel_queries：
  这些查询词用于后续搜索酒店。
  必须满足以下要求：
  1. 优先围绕交通便利、适合游客入住、口碑较好、安全、出行方便的区域或酒店类型。
  2. 可结合用户预算、人数、旅行风格补充商务型、亲子型、度假型、设计型等特征。
  3. 不要加入“免费”“便宜爆款”之类低质量价格描述。
  4. 查询词应偏向“区域 + 酒店特征”或“适合游客入住的住宿选择”。

- must_have：
  表示这次行程中必须覆盖的体验类型，而不是具体店名或具体景点名。
  必须兼顾以下维度中的多个方面：
  1. 核心景点 / 城市名片
  2. 在地餐饮 / 特色美食
  3. 休闲放松 / 城市漫步
  4. 夜间体验 / 夜景 / 夜生活
  5. 如用户有明显偏好，还要覆盖对应体验，例如亲子、艺术、建筑、购物、自然风光等

【生成原则】
1. 优先生成“具体可搜”的查询词，不要生成抽象概念。
2. 优先考虑第一次来这座城市的游客最值得体验的内容；若用户需求明确，则以用户需求优先。
3. 如果用户偏好与城市特色存在交集，优先输出交集内容。
4. 查询词之间要有层次，不要高度重复。
5. 输出内容应符合真实旅行规划场景，避免机械、模板化、空泛词汇。
6. 所有内容使用简体中文。
7. 只输出合法 JSON。
"""
